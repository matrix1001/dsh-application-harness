#!/usr/bin/env node
/**
 * New-application scaffolder. Generates a minimal-but-correct application
 * skeleton per docs/APPLICATION_DEVELOPMENT.md and the architecture doc's
 * application contract (docs/ARCHITECTURE.md):
 *
 *   packages/examples/<app>/    host package: the application DECLARED as data
 *                               (`AppDeclaration` in src/app.ts: platform JSON
 *                               Schema DSL params, one `ping` op) plus the row
 *                               that hands it to the runtime
 *                               (`mountApplication`) with stop and unregister
 *                               tied to plugin disposal
 *   packages/client/<app>-view/ view package: registers the application's page
 *                               into the shell's `applicationViews` registry
 *                               (`ctx.applicationViews.register(appId, …)`) —
 *                               generated by default; `--no-view` skips it
 *
 * and wires the new packages into the repo's build graphs (the host/client
 * tsconfig reference lists + the root tsdown client-bundle enumeration), so
 * `pnpm run typecheck` and `pnpm run build` pick them up without manual
 * editing. Prints the remaining manual steps (the client-edge contract record,
 * tests, coverage).
 *
 * No package README is generated: the project maintains README, AGENTS.md,
 * the architecture doc and the application development guide.
 *
 * Usage:
 *   node scripts/new-app.mjs <app> [--version <v>] [--no-view] [--root <dir>]
 *
 * `--root` scaffolds into an alternate tree and is meant for the script-plane
 * tests (`scripts/tests/new-app-scaffold.test.mjs`); the default root is this
 * checkout.
 *
 * The generated host app declares one `ping` op; replace it with your ops and
 * add `tests/${app}.spec.ts` + per-file 100% coverage.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { declaredLine } from './vendor-platform-src.mjs'

const args = process.argv.slice(2)
/** The value of a `--flag value` / `--flag=value` argument (undefined when absent). */
const valueOf = (flag) => {
  const inline = args.find(a => a.startsWith(`${flag}=`))
  if (inline !== undefined) return inline.slice(flag.length + 1)
  const index = args.indexOf(flag)
  return index < 0 ? undefined : args[index + 1]
}
const noView = args.includes('--no-view')
// The positional appid: the first token that is neither a flag nor a flag's value.
const flagValues = new Set([valueOf('--version'), valueOf('--root')].filter(value => value !== undefined))
const app = args.find(a => !a.startsWith('--') && !flagValues.has(a))
// `--root DIR` scaffolds into an alternate tree. It exists for the script-plane
// tests (a temp root carrying the two tsconfig reference files, the client
// bundle list, the root manifest the cordis pin is read from and the deployment
// descriptor the platform pin is read from), which is the only way to prove
// BOTH products — the default view package and `--no-view` — are born
// gate-clean (AR2 ③, 2026-09-19) and type-checkable.
const rootArg = valueOf('--root')
const ROOT = rootArg === undefined ? join(dirname(fileURLToPath(import.meta.url)), '..') : resolve(rootArg)

if (app === undefined || /[^a-z0-9-]/.test(app) || app.includes('__')) {
  console.error('usage: node scripts/new-app.mjs <app> [--version <v>] [--no-view]\n  <app> = lowercase kebab-case name, no "__" (the tool-name separator).')
  process.exit(1)
}
// The platform pin written into a scaffolded package: read from the descriptor
// (its single home), never a literal that rots past the next bump.
const PLATFORM_LINE = declaredLine(ROOT)
// The platform treats `engines.dsh` as authoritative when present; read the
// range and release-train version from the bundle manifest so a scaffolded app
// cannot drift from the current release line. `--root` fixtures may omit the
// bundle; the fallback keeps those self-contained.
const bundle = (() => {
  try {
    return JSON.parse(readFileSync(join(ROOT, 'packages/bundle/app-harness/package.json'), 'utf8'))
  } catch {
    return undefined
  }
})()
const ENGINE_RANGE = bundle?.engines?.dsh ?? '>=0.2.2-rc.1 <0.3.0-0'
// The cordis pin: read from the root manifest, for the same reason — a `^4.0.2`
// style range never resolves to the alpha prerelease the workspace uses.
const CORDIS_PIN = rootCordisPin(ROOT)
const version = valueOf('--version') ?? bundle?.version ?? '0.1.0'

const write = (path, body) => {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, body, 'utf8')
  console.log(`  + ${path.replace(`${ROOT}/`, '')}`)
}

/** Read the workspace's cordis pin from the root manifest (fail loud when it is not there). */
function rootCordisPin(root) {
  const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
  const pin = manifest.devDependencies?.['@deepseek-ai/cordis'] ?? manifest.dependencies?.['@deepseek-ai/cordis']
  if (typeof pin !== 'string' || pin === '') throw new Error('the root package.json declares no @deepseek-ai/cordis pin to copy')
  return pin
}

/** Insert `line` (comma-less) after the last `{ "path": … }` entry of a references-array file (idempotent). */
const appendReference = (file, line) => {
  const path = join(ROOT, file)
  const text = readFileSync(path, 'utf8')
  const entry = line.trim().replace(/,\s*$/, '')
  const needle = entry.match(/"path":\s*"\.\/([^"]+)"/)?.[1]
  if (needle !== undefined && text.includes(needle)) return // already wired
  const idx = text.lastIndexOf('{ "path":')
  if (idx < 0) throw new Error(`${file}: no { "path": } entry found`)
  const eol = text.indexOf('\n', idx)
  const needsComma = !text.slice(idx, eol).includes(',')
  writeFileSync(path, text.slice(0, eol) + (needsComma ? ',' : '') + '\n' + entry + '\n' + text.slice(eol + 1), 'utf8')
  console.log(`  ~ ${file} (references += ${needle ?? entry})`)
}

console.log(`Scaffolding application "${app}"${noView ? '' : ' + view'}@${version}\n`)

// ---- host package ---------------------------------------------------------
const host = join(ROOT, 'packages/examples', app)
write(join(host, 'package.json'), JSON.stringify({
  name: `@matrix1001/dsh-application-harness-${app}`,
  version,
  description: `The ${app} example application`,
  type: 'module',
  main: 'lib/index.js',
  types: 'lib/types/index.d.ts',
  exports: {
    '.': { types: './lib/types/index.d.ts', default: './lib/index.js' },
    './package.json': './package.json',
  },
  files: [
    'lib/index.js',
    'lib/types/**/*.d.ts',
  ],
  license: 'MIT',
  engines: { dsh: ENGINE_RANGE },
  // The runtime package the declaration is written in (`AppDeclaration`,
  // `AppError`): a workspace peer, mirrored into dev for the local build.
  peerDependencies: {
    '@matrix1001/dsh-application-harness-runtime': 'workspace:*',
    '@deepseek-ai/cordis': CORDIS_PIN,
  },
  devDependencies: {
    '@matrix1001/dsh-application-harness-runtime': 'workspace:*',
    '@deepseek-ai/cordis': CORDIS_PIN,
  },
  // 挂载行由 generate-bundle-patch.mjs 聚合；部署集合仍需在 deployment.yml 声明。
  dsh: { appRow: { id: app, name: `@matrix1001/dsh-application-harness-${app}` } },
}, null, 2) + '\n')
write(join(host, 'tsconfig.json'), JSON.stringify({
  extends: '../../../tsconfig.base.json',
  compilerOptions: { rootDir: 'src', outDir: 'lib/types' },
  include: ['src'],
  references: [
    { path: '../../application/runtime' },
  ],
}, null, 2) + '\n')
write(join(host, 'src/app.ts'), `/**
 * The ${app} application, declared once: identity, operations, and what it
 * needs. Every caller — the human's own page, the AI's tools, another
 * application — arrives through these operations, and the parameters and
 * results are declared in the PLATFORM's JSON Schema DSL (the same vocabulary
 * the platform's tools use), so one declaration feeds the remote face, the AI
 * tool face and the permission check.
 * @module
 */

import { AppError } from '@matrix1001/dsh-application-harness-runtime'
import type { AppDeclaration } from '@matrix1001/dsh-application-harness-runtime'

/**
 * Build the application declaration.
 * @returns the declaration the runtime registers.
 */
export function ${pascal(app)}Declaration(): AppDeclaration {
  return {
    id: '${app}',
    name: '${app}',
    description: '…',
    version: '${version}',
    ops: {
      ping: {
        description: 'Echo a message back',
        params: {
          message: { type: 'string', required: true, description: 'The message to echo' },
        },
        result: {
          type: 'object',
          additionalProperties: true,
          properties: { echo: { type: 'string', description: 'The message, unchanged' } },
        },
        // Closed to the AI by default: the human page calls the operation
        // directly, and the author opens it to the model only after reviewing
        // it (open for safe/core work, confirm for destructive work).
        exposure: { ai: 'closed' },
        execute: (args) => {
          const message = (args as { message?: unknown }).message
          // The runtime already refuses a missing/ill-typed \`message\` against
          // the declaration; this is the shape of a business refusal.
          if (typeof message !== 'string') throw new AppError('invalid-args', 'ping requires message to be a string')
          return { echo: message }
        },
      },
    },
  }
}
`)
write(join(host, 'src/index.ts'), `/**
 * The ${app} Cordis plugin. The shared mount helper ties application startup,
 * cancellation, stop and unregister to this plugin's lifetime.
 * @module @matrix1001/dsh-application-harness-${app}
 */

import type { Context } from '@deepseek-ai/cordis'
import { mountApplication } from '@matrix1001/dsh-application-harness-runtime'
import { ${pascal(app)}Declaration } from './app.ts'

/** The plugin name. */
export const name = '${app}'

/** Required runtime service. */
export const inject = ['applications']

/** Mount the application; its start hook settles independently of the row. */
export async function apply(ctx: Context): Promise<void> {
  await mountApplication(ctx, ${pascal(app)}Declaration())
}

export { ${pascal(app)}Declaration } from './app.ts'
`)

// Wire the host package into the host typecheck aggregate.
appendReference('tsconfig.host.json', `    { "path": "./packages/examples/${app}" }`)

// ---- client view package (optional) ---------------------------------------
if (!noView) {
  const view = join(ROOT, 'packages/client', `${app}-view`)
  write(join(view, 'package.json'), JSON.stringify({
    name: `@matrix1001/dsh-application-harness-${app}-view`,
    version,
    description: `The ${app} application page for the applications shell`,
    type: 'module',
    main: 'lib/index.js',
    types: 'lib/types/index.d.ts',
    exports: {
      '.': { types: './lib/types/index.d.ts', default: './lib/index.js' },
      './client': { types: './lib/types/client/index.d.ts', default: './lib/client.js' },
      './src/*': './src/*',
      './package.json': './package.json',
    },
    files: [
      'lib/index.js',
      'lib/client.js',
      'lib/types/**/*.d.ts',
    ],
    license: 'MIT',
    engines: { dsh: ENGINE_RANGE },
    // The page registers into the shell's `applicationViews` registry; the row
    // carries the application id it draws (`dsh.appRow.appId`), so a view row
    // without its host row can never match.
    dsh: {
      client: { inject: [], platform: 'web' },
      appRow: { id: `client-ui-${app}`, name: `@matrix1001/dsh-application-harness-${app}-view`, appId: app },
    },
    scripts: { bundle: 'tsdown', watch: 'tsdown --watch' },
    // Peers are Cordis-only for a client plugin (`scripts/verify-client-peer-shape.mjs`):
    // the shell is a TYPE/browser edge the consumer's bundle supplies, so it lives
    // in devDependencies (and in the tsconfig references), never in peers — a
    // workspace peer of a type-only edge breaks npm consumption (AR2 ③, 2026-09-19).
    peerDependencies: {
      '@deepseek-ai/cordis': CORDIS_PIN,
    },
    devDependencies: {
      '@matrix1001/dsh-application-harness-client-applications': 'workspace:*',
      '@deepseek-ai/cordis': CORDIS_PIN,
      '@deepseek-ai/dsh-client-locale': PLATFORM_LINE,
      '@deepseek-ai/dsh-client-ui-slots': PLATFORM_LINE,
      '@types/react': '~18.3.1',
      '@types/react-dom': '~18.3.1',
      'react': '^18.2.0',
      'react-dom': '^18.2.0',
    },
  }, null, 2) + '\n')
  write(join(view, 'tsconfig.json'), JSON.stringify({
    extends: '../../../tsconfig.base.client.json',
    compilerOptions: { rootDir: 'src', outDir: 'lib/types' },
    include: ['src'],
    references: [
      { path: '../applications' },
    ],
  }, null, 2) + '\n')
  write(join(view, 'src/index.ts'), `/**
 * ${app} application page plugin, node half. Pure UI plugin: the empty apply
 * exists so the plugin appears in the host cordis.yml / Loader; the browser
 * half ships via exports["./client"], discovered through the package.json
 * dsh.client declaration.
 * @module @matrix1001/dsh-application-harness-${app}-view
 */

/** Host plugin body — no host-side behavior for this source plugin. */
export function apply(): void {}
`)
  write(join(view, 'src/client/locales.ts'), `/** \`${app}\` namespace dictionaries. */

/** Dictionary namespace owned by this plugin. */
export const NS = '${app}'

/** Simplified Chinese dictionary (the key-set source of truth). */
export const zh = {
  // The name and the one-line description the shell shows wherever it names
  // this application (navigation, switcher, management list and its header).
  'app.name': '${app} 应用',
  'app.description': '一句话说明这个应用做什么。',
  'view.hint': '这是脚手架生成的页面；把它换成你自己的界面。',
  'view.ping': '调用 ping',
  'view.answer': '结果',
  'view.cancelled': '已取消',
}

/** English dictionary (same key set). */
export const en: Record<${pascal(app)}Key, string> = {
  'app.name': '${app} application',
  'app.description': 'One line about what this application is for.',
  'view.hint': 'This page was generated by the scaffolder; replace it with your own interface.',
  'view.ping': 'Call ping',
  'view.answer': 'Result',
  'view.cancelled': 'Cancelled',
}

/** Dictionary key type. */
export type ${pascal(app)}Key = keyof typeof zh
`)
  write(join(view, `src/client/${pascal(app)}View.tsx`), `import { useCallback, useState, useSyncExternalStore } from 'react'
import type { LocaleRuntime } from '@deepseek-ai/dsh-client-locale/client'
import type { TranslateNS } from '@deepseek-ai/dsh-client-ui-slots'
import type { ApplicationViewProps } from '@matrix1001/dsh-application-harness-client-applications/client'
import { NS } from './locales.ts'

/** The translate face this page needs: this package's locale seat. */
export type ${pascal(app)}Translate = TranslateNS<'${app}'>

/** The props of the registered page: the shell's view face plus the locale service. */
export interface ${pascal(app)}PageProps extends ApplicationViewProps {
  /** The client locale service (the registration binds the dictionary through it). */
  locale: LocaleRuntime
}

/** The props of the page body: the shell's call face plus its own translator. */
export interface ${pascal(app)}ViewProps extends ApplicationViewProps {
  /** This package's bound translator (a language switch repaints through it). */
  t: ${pascal(app)}Translate
}

/**
 * The registered page: bind this package's dictionary to the viewer's locale
 * and render the page body. The locale subscription is what makes a language
 * switch repaint the page.
 * @param props - the shell's view face plus the locale service.
 * @returns the ${app} page.
 */
export function ${pascal(app)}Page({ locale, ...props }: ${pascal(app)}PageProps) {
  useSyncExternalStore(
    useCallback((listener: () => void) => locale.subscribe(listener), [locale]),
    useCallback(() => locale.getSnapshot(), [locale]),
  )
  return <${pascal(app)}View {...props} t={locale.bind(NS)} />
}

/**
 * The ${app} page body: one \`ping\` call through the shell's call face (the
 * outcome is the runtime's own four-way result). Replace this with your own UI.
 * @param props - the call face, the in-flight flag and the translator.
 * @returns the page body.
 */
export function ${pascal(app)}View({ call, running, t }: ${pascal(app)}ViewProps) {
  const [answer, setAnswer] = useState('')

  const onPing = useCallback(async () => {
    const outcome = await call('ping', { message: 'hello from the page' })
    if (outcome.status === 'success') setAnswer(JSON.stringify(outcome.result))
    else if (outcome.status === 'cancelled') setAnswer(t('view.cancelled'))
    else setAnswer(\`\${outcome.status}: \${outcome.error?.message ?? ''}\`)
  }, [call, t])

  // No application-name heading here: the shell's own header already names the
  // application; the architecture's page-frame contract forbids repeating it
  // inside the body.
  return (
    <section style={{ display: 'grid', gap: 8, padding: 16 }}>
      <p>{t('view.hint')}</p>
      <div>
        <button type="button" disabled={running} onClick={() => { void onPing() }}>
          {t('view.ping')}
        </button>
      </div>
      <p>{t('view.answer')}: {answer === '' ? '—' : answer}</p>
    </section>
  )
}
`)
  write(join(view, 'src/client/index.ts'), `/**
 * ${app} application page plugin, browser half: registers the \`${app}\` page
 * into the applications shell's \`applicationViews\` registry (one view per
 * appId) and the package's \`${app}\` locale dictionaries.
 *
 * The registration is the whole wiring: the framework hands the page its
 * \`ApplicationViewProps\` (call/cancel/onChanged/running, the page-context face
 * and this application's own \`ui\` view state), and this package's page reads
 * the application through that one face — no projection, no world slot. An
 * application with real settings registers a \`Settings\` half beside
 * \`Component\`; one without it simply omits the field.
 */
import { createElement } from 'react'
import type { Context } from '@deepseek-ai/cordis'
import { ${pascal(app)}Page } from './${pascal(app)}View.tsx'
import { en, NS, type ${pascal(app)}Key, zh } from './locales.ts'
// Type-only: pulls the applications shell's Context merge (\`ctx.applicationViews\`)
// and the registration contract into this face. The behaviour rides the
// service; this package never value-imports the shell.
import type {} from '@matrix1001/dsh-application-harness-client-applications/client'
import type { ApplicationView } from '@matrix1001/dsh-application-harness-client-applications/client'
// Type-only: pulls the locale plugin's Context merge (ctx.locale).
import type {} from '@deepseek-ai/dsh-client-locale/client'

declare module '@deepseek-ai/dsh-client-ui-slots' {
  interface LocaleNamespaceMap {
    /** ${pascal(app)} page copy. */
    '${app}': ${pascal(app)}Key
  }
}

export type { ${pascal(app)}Key } from './locales.ts'
export { ${pascal(app)}View } from './${pascal(app)}View.tsx'
export type { ${pascal(app)}ViewProps } from './${pascal(app)}View.tsx'

/** Required services: the locale dictionaries and the applications shell's view registry. */
export const inject = ['locale', 'applicationViews']

/** The application id this package draws the page of. */
const APP_ID = '${app}'

/**
 * Client plugin body: register the dictionaries and the ${app} page.
 * @param ctx - client root context.
 */
export function apply(ctx: Context): void {
  ctx.effect(() => ctx.locale.register(NS, { zh, en }), 'ui-${app}: dictionaries')

  // The name and the description are getters over the dictionary: the
  // registration runs once, a language switch happens later, and the shell
  // reads them per render. An application with its own glyph declares \`icon\`
  // (and a semantic \`tone\`) beside them.
  const t = ctx.locale.bind(NS)
  const view: ApplicationView = {
    name: () => t('app.name'),
    description: () => t('app.description'),
    Component: props => createElement(${pascal(app)}Page, { ...props, locale: ctx.locale }),
  }
  // Fiber-owned: the page unregisters with the plugin (HMR safety), and the
  // registry itself rejects a second view for the same appId (a silent
  // override would hide a package conflict).
  ctx.effect(() => ctx.applicationViews.register(APP_ID, view), 'ui-${app}: page')
}
`)
  write(join(view, 'tsdown.config.ts'), `import { clientBundle, clientExternalFromPkg } from '../tsdown.client.ts'

// The view value-imports nothing from other bundles today, but the seam is
// read from the manifest (one source) so the purity gate externalizes a
// declared dsh.client.external edge if an infrastructure value import is
// added later (inject stays informational — not a build seam).
export default clientBundle('@matrix1001/dsh-application-harness-${app}-view', ['lib/types/index.js'], {
  clientExternal: clientExternalFromPkg(import.meta.url),
})
`)

  // Wire the view package into the client typecheck aggregate and the root
  // client-bundle enumeration.
  appendReference('tsconfig.client.json', `    { "path": "./packages/client/${app}-view" }`)
  const tsdown = join(ROOT, 'tsdown.config.ts')
  const tdText = readFileSync(tsdown, 'utf8')
  if (!tdText.includes(`'packages/client/${app}-view'`)) {
    // Append to the CLIENT_WORKSPACE array (the packages the client pass
    // builds): anchor on the declaration itself, not on a neighbour entry —
    // a hardcoded neighbour keeps matching after the entry it names is gone,
    // and the replace then silently does nothing.
    const block = /(const CLIENT_WORKSPACE = \[[\s\S]*?)(\n\] as const)/u
    if (!block.test(tdText)) throw new Error('tsdown.config.ts no longer declares CLIENT_WORKSPACE as a const array — update scripts/new-app.mjs')
    writeFileSync(tsdown, tdText.replace(block, `$1\n  'packages/client/${app}-view',$2`), 'utf8')
    console.log(`  ~ tsdown.config.ts (client workspace += packages/client/${app}-view)`)
  }
}

console.log('\n接下来：')
console.log(`  1. 实现 packages/examples/${app}/src/app.ts 并补齐业务测试${noView ? '' : '和视图测试'}；覆盖率要求见 vitest.config.ts。`)
console.log(`  2. 在 packages/bundle/app-harness/deployment.yml 的 applications 声明 ${app}${noView ? '' : `，并把 @matrix1001/dsh-application-harness-${app}-view 加入 client.packages`}。`)
if (!noView) {
  console.log(`  3. 在 scripts/inject-contract.json 的 inject 中加入 "@matrix1001/dsh-application-harness-${app}-view": []。`)
}
console.log('  完整步骤见 docs/APPLICATION_DEVELOPMENT.md：补齐数据声明、读写语义、分层清单与测试，再生成、构建、检查和刷新 profile。')
console.log('  node scripts/deps.mjs → node scripts/generate-bundle-patch.mjs → pnpm run build')
console.log('  检查通过后：pnpm run setup --no-build，再 pnpm start。')

function pascal(s) { return s.split('-').map(x => x[0].toUpperCase() + x.slice(1)).join('') }
